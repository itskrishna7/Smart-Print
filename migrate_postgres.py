def _hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(
        password.encode("utf-8"),
        salt=salt,
        n=2**14,
        r=8,
        p=1,
        dklen=32,
    )
    return "scrypt${}${}".format(
        base64.urlsafe_b64encode(salt).decode("ascii"),
        base64.urlsafe_b64encode(digest).decode("ascii"),
    )


def run_migrations(database_url: str, *, dry_run: bool) -> None:
    if dry_run:
        print(f"Dry run: {len(SCHEMA_STATEMENTS)} additive PostgreSQL statements would run.")
        return

    with psycopg.connect(
        database_url,
        connect_timeout=15,
        sslmode="require",
        options="-c timezone=UTC",
    ) as connection:
        with connection.cursor() as cursor:
            for statement in SCHEMA_STATEMENTS:
                cursor.execute(statement)

            cursor.execute("SELECT owner_id, password FROM shop_owners")
            for owner_id, stored_password in cursor.fetchall():
                if stored_password and not stored_password.startswith("scrypt$"):
                    cursor.execute(
                        "UPDATE shop_owners SET password = %s WHERE owner_id = %s",
                        (_hash_password(stored_password), owner_id),
                    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Apply the additive schema changes; otherwise only report the plan.",
    )
    parser.add_argument(
        "--target-environment",
        choices=("test", "production"),
        help="Required with --apply; production also requires --confirm-production.",
    )
    parser.add_argument("--neon-project-id", help="Neon project ID owning the target branch.")
    parser.add_argument("--neon-branch-id", help="Neon branch ID targeted by this migration.")
    parser.add_argument(
        "--confirm-production",
        action="store_true",
        help="Confirm that production schema changes are explicitly authorized.",
    )
    args = parser.parse_args()

    if args.apply and not args.target_environment:
        parser.error("--apply requires an explicit --target-environment.")
    if args.apply and args.target_environment == "production" and not args.confirm_production:
        parser.error("production requires --confirm-production.")
    if args.confirm_production and args.target_environment != "production":
        parser.error("--confirm-production is only valid for a production target.")
    if args.apply and not args.neon_project_id:
        parser.error("--apply requires --neon-project-id.")
    if args.apply and not args.neon_branch_id:
        parser.error("--apply requires --neon-branch-id.")
    if not args.apply:
        run_migrations("", dry_run=True)
        return 0

    database_url = os.getenv("DATABASE_URL_UNPOOLED", "").strip()
    if not database_url:
        parser.error("Set DATABASE_URL_UNPOOLED to the direct Neon PostgreSQL URL.")

    try:
        verify_neon_target(
            database_url,
            args.target_environment,
            args.neon_project_id,
            args.neon_branch_id,
        )
        run_migrations(database_url, dry_run=False)
    except NeonTargetError as error:
        print(f"PostgreSQL schema migration blocked: {error}", file=sys.stderr)
        return 1
    except Exception as error:
        print(f"PostgreSQL schema migration failed: {type(error).__name__}.", file=sys.stderr)
        return 1
    print("Additive PostgreSQL schema migration completed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
